const savedLang = localStorage.getItem('padelconnect_lang') || 'fr';

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: savedLang,
    fallbackLng: 'fr',
    interpolation: { escapeValue: false },
  });

// Sync <html dir> and <html lang> on init
document.documentElement.lang = savedLang;
document.documentElement.dir  = savedLang === 'ar' ? 'rtl' : 'ltr';

export function setLanguage(lang) {
  localStorage.setItem('padelconnect_lang', lang);
  document.documentElement.lang = lang;
  document.documentElement.dir  = lang === 'ar' ? 'rtl' : 'ltr';
  // Nuclear option: reload so every component picks up the new language cleanly
  window.location.reload();
}

export default i18n;
